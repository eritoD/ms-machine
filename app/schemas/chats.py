"""Chat list (HU-49). The JSON uses camelCase because that is the contract the
app was given for this endpoint; the rest of this service speaks snake_case."""
import re
from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator
from pydantic.alias_generators import to_camel

_FILE_NAME = re.compile(r"^[^\x00-\x1f\x7f/\\]+$")


class ChatParticipant(BaseModel):
    userId: UUID
    name: str
    avatarUrl: str | None


class ChatLastMessage(BaseModel):
    # For an image, file or location without caption this is a short label ("Imagen", "Archivo", "Ubicación").
    content: str
    senderId: UUID
    createdAt: datetime
    type: Literal["TEXT", "IMAGE", "LOCATION", "FILE"] = "TEXT"


class ChatSummary(BaseModel):
    """One active conversation (an accepted match) as the person sees it in their chat list."""

    conversationId: UUID
    participant: ChatParticipant
    lastMessage: ChatLastMessage | None
    unreadCount: int


class ReadResult(BaseModel):
    conversationId: UUID
    markedAsRead: int
    unreadCount: int


class ChatMessageCreate(BaseModel):
    """Message to send in a conversation (HU-50). Accepts camelCase (the contract) and snake_case.

    TEXT: `content`. IMAGE / FILE: `attachmentUrl` (+ optional caption in `content`, optional
    `attachmentName` for files). LOCATION: `latitude` and `longitude` (+ optional `locationName`
    and `content`). Anything that does not belong to the type is rejected."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True, alias_generator=to_camel,
                              populate_by_name=True)
    type: Literal["TEXT", "IMAGE", "LOCATION", "FILE"] = "TEXT"
    content: str | None = Field(default=None, max_length=2000)
    latitude: float | None = Field(default=None, ge=-90, le=90, allow_inf_nan=False)
    longitude: float | None = Field(default=None, ge=-180, le=180, allow_inf_nan=False)
    location_name: str | None = Field(default=None, max_length=120)
    attachment_url: str | None = Field(default=None, max_length=2048)
    attachment_name: str | None = Field(default=None, max_length=120)
    # Lets the app retry a send without duplicating it; generated by the server when omitted.
    client_message_id: UUID | None = None

    @field_validator("content", "location_name", "attachment_url", "attachment_name")
    @classmethod
    def blank_is_none(cls, value):
        return value or None

    @field_validator("latitude", "longitude")
    @classmethod
    def metre_precision(cls, value):
        return None if value is None else round(value, 6)  # 6 decimals is about 0.1 m

    @field_validator("attachment_name")
    @classmethod
    def plain_file_name(cls, value):
        if value is not None and not _FILE_NAME.match(value):
            raise ValueError("El nombre del archivo no puede incluir barras ni caracteres de control.")
        return value

    @model_validator(mode="after")
    def only_what_the_type_carries(self):
        given = {name for name in ("content", "latitude", "longitude", "location_name", "attachment_url",
                                   "attachment_name") if getattr(self, name) is not None}
        needs = {"TEXT": {"content"}, "IMAGE": {"attachment_url"}, "FILE": {"attachment_url"},
                 "LOCATION": {"latitude", "longitude"}}[self.type]
        allowed = needs | {"TEXT": set(), "IMAGE": {"content"}, "FILE": {"content", "attachment_name"},
                           "LOCATION": {"content", "location_name"}}[self.type]
        if needs - given:
            raise ValueError(f"Un mensaje {self.type} necesita: {', '.join(sorted(needs - given))}.")
        if given - allowed:
            raise ValueError(f"Un mensaje {self.type} no admite: {', '.join(sorted(given - allowed))}.")
        return self
